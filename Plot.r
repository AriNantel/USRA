# Define the system of ODEs according to barry saltzman equations
saltzman_system <- function(t, state, parameters) {
  x <- state[1]
  y <- state[2]
  z <- state[3]

  dx <- -x - y - v * z
  dy <- -p * z + r * y - s * y^2 - y^3
  dz <- -q * (x + z)

  list(c(dx, dy, dz))
}

